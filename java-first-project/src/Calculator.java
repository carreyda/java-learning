public class Calculator {
//    public class salculator {  类'salculator'为 public，应在文件'salculatorjava'中声明
    public static void main(String[] args) { // 程序入口方法，固定写法
//        public static void main(string[] args) 无法解析符号 'string'
        System.out.println(10 + 3); // 打印一行并换行
        System.out.println(10 - 3);
        System.out.println(10 * 3);
        System.out.println(10 / 3);
        System.out.println(10 % 3);
        System.out.println(10.0 / 3);
//        System.out.println(10.0 / 3) java: 需要';'

    } // main 方法结束
}
